"""Convert 老王指弹改编版.gp5 bars 96-108 (原曲 rap 段) into laowang.py, halving note values to match ♩=84."""
import guitarpro as gp

FIRST, LAST = 96, 108
BASS_CHORD = {(6, 0): "Em", (5, 3): "C", (6, 3): "G", (4, 0): "D"}
UNITS = {4: 2, 8: 1, 16: 0.5}        # GP note value -> 16th units after halving

s = gp.parse("平凡之路指弹改编版.gp5")
prev_chord, prev_ts = None, None
lines = ['"""Generated by gp2data.py from 吉他社《平凡之路指弹改编版》(老王) bars 96-108 — do not edit."""',
         "from data import E, Bar, DEAD", "", "LAOWANG = ["]
for m, h in zip(s.tracks[0].measures, s.measureHeaders):
    if not FIRST <= h.number <= LAST:
        continue
    num, den = h.timeSignature.numerator, h.timeSignature.denominator.value
    evs = []
    for beat in m.voices[0].beats:
        d = UNITS[beat.duration.value] * (1.5 if beat.duration.isDotted else 1)
        if beat.status == gp.BeatStatus.rest or not beat.notes:
            evs.append(f"E({d!r}, rest=True)")
            continue
        notes, chord = [], None
        for n in sorted(beat.notes, key=lambda n: n.string):
            txt = "DEAD" if n.type == gp.NoteType.dead else repr(str(n.value))
            notes.append(f"({n.string}, {txt})")
            chord = chord or BASS_CHORD.get((n.string, n.value))
        if chord == prev_chord:
            chord = None
        elif chord:
            prev_chord = chord
        evs.append(f"E({d!r}, [{', '.join(notes)}]" + (f", {chord!r}" if chord else "") + ")")
    ts = (num, den * 2)
    lines.append(f"    Bar([{', '.join(evs)}]" + (f", ts={ts}" if ts != prev_ts else "") + f"),  # 老王 {h.number}")
    prev_ts = ts
lines.append("]")
open("laowang.py", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines))
