def E(d, notes=(), chord=None, tech=None, tie=False, strum=None, arp=False, rest=False, harm=False, rng=(1, 6),
      acc=False):
    return dict(d=d, n=list(notes), chord=chord, tech=tech, tie=tie, strum=strum, arp=arp, rest=rest, harm=harm,
                rng=rng, acc=acc)


class Bar(list):
    """A measure: list of events + lyrics [(event index (float ok), text)] + end-barline style."""
    def __init__(self, events, ly=(), end=None, ts=None):
        super().__init__(events)
        self.ly = list(ly)
        self.end = end            # None | "double"
        self.ts = ts              # time signature shown at the start of this bar


def xs(a, b):
    return [(s, X) for s in range(a, b + 1)]


# ---------------------------------------------------------------- 大树音乐屋 patterns
def pA(c1="Em", c2="Cadd9"):
    return [E(2, [(6, X)], c1), E(2, [(4, X)]), E(2, [(2, X)]), E(2, [(3, X)]),
            E(2, [(5, X)], c2), E(2, [(4, X)]), E(2, [(2, X)]), E(2, [(3, X)])]


def pB():
    return [E(2, [(6, X)], "G6add9"), E(2, [(4, X)]), E(2, [(2, X)]), E(2, [(3, X)]),
            E(2, [(6, "2")]), E(2, [(3, "0")]), E(2, [(3, "2")]), E(2, [(4, "0")])]


def pA2():  # 主歌二：2、3 弦带切音的小扫弦
    return [E(2, [(6, X)], "Em"), E(2, [(4, X)]), E(2, xs(2, 3), strum="up", rng=(2, 3), acc=True), E(2, [(3, X)]),
            E(2, [(5, X)], "Cadd9"), E(2, [(4, X)]), E(2, xs(2, 3), strum="up", rng=(2, 3), acc=True), E(2, [(3, X)])]


def pB2(last=False):
    ev = [E(2, [(6, X)], "G6add9"), E(2, [(4, X)]), E(2, xs(2, 3), strum="up", rng=(2, 3), acc=True), E(2, [(3, X)]),
          E(2, [(6, "2")]), E(2, [(3, "0")]), E(2, [(3, "2"), (4, "0")], strum="up", rng=(3, 4), acc=True)]
    return ev + ([E(2, rest=True)] if last else [E(2, [(4, "0")])])


def pC(c1, c2, low1=(5, 6), low2=(5, 6), top1=6):
    """副歌扫弦：每小节 11 下，c1 占前两拍，c2 占后两拍。"""
    return [E(2, xs(1, top1), c1, strum="up", rng=(1, top1)), E(2, xs(*low1), strum="up", rng=low1),
            E(2, xs(1, 5), strum="up", rng=(1, 5)), E(1, xs(1, 4), strum="up", rng=(1, 4)),
            E(1, xs(1, 4), strum="down", rng=(1, 4)),
            E(1, xs(1, 5), c2, strum="up", rng=(1, 5)), E(1, xs(1, 4), strum="down", rng=(1, 4)),
            E(2, xs(*low2), strum="up", rng=low2),
            E(2, xs(1, 5), strum="up", rng=(1, 5)), E(1, xs(1, 4), strum="up", rng=(1, 4)),
            E(1, xs(1, 4), strum="down", rng=(1, 4))]


